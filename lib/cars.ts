/** Cars grouped by make: biggest groups first, then A to Z. */
export function carsByMake(): { make: string; slug: string; cars: Car[] }[] {
  const groups = new Map<string, Car[]>();
  for (const car of cars) groups.set(car.make, [...(groups.get(car.make) ?? []), car]);
  return [...groups.entries()]
    .sort(([a, x], [b, y]) => y.length - x.length || a.localeCompare(b))
    .map(([make, list]) => ({
      make,
      slug: make.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
      cars: list,
    }));
}
